import AppKit

struct ClipItem: Identifiable {
    enum Content {
        case text(String)
        case image(Data, NSPasteboard.PasteboardType)
        case files([URL])
    }

    let id = UUID()
    let content: Content
    /// What makes two clips "the same", so copying something again moves it to the front.
    let key: String
    let preview: NSImage?
    let appBundleID: String?
    var date: Date

    var text: String? { if case .text(let text) = content { return text }; return nil }
}

/// The last 30 things you copied, kept in memory only (never written to disk). Anything a
/// password manager marks as concealed or transient is skipped.
@Observable @MainActor
final class ClipboardHistory {
    static let limit = 30
    static let imageLimit = 10

    private(set) var items: [ClipItem] = []
    private(set) var selection: Set<UUID> = []
    @ObservationIgnored private var anchor: UUID?
    @ObservationIgnored var announce: (String) -> Void = { _ in }
    @ObservationIgnored private var lastChange = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?

    private static let skippedTypes: [NSPasteboard.PasteboardType] = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ].map { NSPasteboard.PasteboardType($0) }

    var selectedItems: [ClipItem] { items.filter { selection.contains($0.id) } }

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        guard Prefs.bool(Prefs.clipboardHistory) else { return }
        let types = pasteboard.types ?? []
        guard !types.contains(where: Self.skippedTypes.contains), let item = Self.capture(pasteboard) else { return }
        add(item)
    }

    /// Files first, then text, then images: rich text often carries a picture of itself too.
    static func capture(_ pasteboard: NSPasteboard) -> ClipItem? {
        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return ClipItem(content: .files(urls), key: "files:" + urls.map(\.path).joined(separator: "|"),
                            preview: NSWorkspace.shared.icon(forFile: urls[0].path), appBundleID: app, date: Date())
        }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return ClipItem(content: .text(text), key: "text:" + text, preview: nil, appBundleID: app, date: Date())
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] {
            if let data = pasteboard.data(forType: type), let image = NSImage(data: data) {
                let fingerprint = data.prefix(4096).reduce(into: UInt64(data.count)) { $0 = $0 &* 31 &+ UInt64($1) }
                return ClipItem(content: .image(data, type), key: "image:\(fingerprint)", preview: image,
                                appBundleID: app, date: Date())
            }
        }
        return nil
    }

    /// Newest first; copying the same thing again moves it back to the front.
    func add(_ item: ClipItem) {
        if let existing = items.firstIndex(where: { $0.key == item.key }) {
            var moved = items.remove(at: existing)
            moved.date = Date()
            items.insert(moved, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        var images = 0
        items = items.filter {
            guard case .image = $0.content else { return true }
            images += 1
            return images <= Self.imageLimit
        }
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
        selection = selection.filter { id in items.contains { $0.id == id } }
    }

    // MARK: Selection

    /// Like the Tray: a plain click selects the clip (and copies it straight away), ⌘-click adds
    /// or removes one, ⇧-click selects a range.
    func click(_ item: ClipItem, command: Bool, shift: Bool) {
        if shift, let anchor,
           let from = items.firstIndex(where: { $0.id == anchor }),
           let to = items.firstIndex(where: { $0.id == item.id }) {
            let range = Set(items[min(from, to)...max(from, to)].map(\.id))
            selection = command ? selection.union(range) : range
            return
        }
        if command {
            if selection.contains(item.id) { selection.remove(item.id) } else { selection.insert(item.id) }
        } else {
            selection = [item.id]
            copy([item])
        }
        anchor = item.id
    }

    func setSelection(_ ids: Set<UUID>) {
        if ids != selection { selection = ids }
    }

    func selectAll() { selection = Set(items.map(\.id)) }

    func clearSelection() {
        if !selection.isEmpty { selection.removeAll() }
    }

    // MARK: Actions

    /// Puts clips back on the clipboard. Several text clips become one block of text.
    func copy(_ chosen: [ClipItem]) {
        guard !chosen.isEmpty else { return }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        let texts = chosen.compactMap(\.text)
        if texts.count == chosen.count {
            pasteboard.setString(texts.joined(separator: "\n"), forType: .string)
        } else if chosen.count == 1, case .image(let data, let type) = chosen[0].content {
            pasteboard.setData(data, forType: type)
        } else {
            var objects: [NSPasteboardWriting] = []
            for item in chosen {
                switch item.content {
                case .text(let text): objects.append(text as NSString)
                case .image(let data, _): if let image = NSImage(data: data) { objects.append(image) }
                case .files(let urls): objects += urls.map { $0 as NSURL }
                }
            }
            pasteboard.writeObjects(objects)
        }
        lastChange = pasteboard.changeCount  // our own write isn't a new clip (and doesn't reorder)
        announce(chosen.count == 1 ? "Copied" : "Copied \(chosen.count) clips")
    }

    func remove(_ chosen: [ClipItem]) {
        let ids = Set(chosen.map(\.id))
        items.removeAll { ids.contains($0.id) }
        selection.subtract(ids)
    }

    /// Delete key: removes whatever is selected. Returns how many clips went.
    @discardableResult
    func removeSelected() -> Int {
        let chosen = selectedItems
        remove(chosen)
        return chosen.count
    }

    func clear() {
        items.removeAll()
        selection.removeAll()
    }
}
